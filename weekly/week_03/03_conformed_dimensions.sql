-- ----------------------------------------------------------------------------
-- 4. ELT TRANSFORMATION PIPELINES (Populate Dimensions from Live 3NF Tables)
-- ----------------------------------------------------------------------------

-- A) Load dim_customer with Window Function Address Deduplication
WITH ranked_addresses AS (
    SELECT 
        customer_id,
        address_line_1,
        city,
        state,
        postal_code,
        country,
        ROW_NUMBER() OVER (
            PARTITION BY customer_id 
            ORDER BY is_default DESC, created_at DESC
        ) AS addr_rank
    FROM customer.addresses
)
INSERT INTO dwh.dim_customer (
    customer_id, customer_code, full_name, first_name, last_name,
    email, phone, customer_status, signup_date,
    address_line_1, city, state, postal_code, country
)
SELECT 
    c.customer_id,
    c.customer_code,
    c.first_name || ' ' || c.last_name AS full_name,
    c.first_name,
    c.last_name,
    c.email,
    COALESCE(c.phone, 'N/A'),
    c.customer_status,
    c.signup_date::DATE,
    COALESCE(a.address_line_1, 'No Address Provided'),
    COALESCE(a.city, 'Unknown City'),
    COALESCE(a.state, 'Unknown State'),
    COALESCE(a.postal_code, 'N/A'),
    COALESCE(a.country, c.country, 'Unknown Country')
FROM customer.customers c
LEFT JOIN ranked_addresses a 
    ON c.customer_id = a.customer_id AND a.addr_rank = 1
ON CONFLICT (customer_id) 
DO UPDATE SET
    full_name = EXCLUDED.full_name,
    email = EXCLUDED.email,
    customer_status = EXCLUDED.customer_status,
    address_line_1 = EXCLUDED.address_line_1,
    city = EXCLUDED.city,
    state = EXCLUDED.state,
    postal_code = EXCLUDED.postal_code,
    country = EXCLUDED.country,
    dw_updated_at = CURRENT_TIMESTAMP;

-- B) Load dim_product (Denormalizing Categories)
INSERT INTO dwh.dim_product (
    product_id, sku, product_name, brand,
    category_name, cost_price, product_status, launch_date
)
SELECT 
    p.product_id,
    p.sku,
    p.product_name,
    p.brand,
    COALESCE(cat.category_name, 'Uncategorized'),
    p.cost_price,
    p.status AS product_status,
    p.launch_date
FROM catalog.products p
LEFT JOIN catalog.categories cat ON p.category_id = cat.category_id
ON CONFLICT (product_id)
DO UPDATE SET
    sku = EXCLUDED.sku,
    product_name = EXCLUDED.product_name,
    brand = EXCLUDED.brand,
    category_name = EXCLUDED.category_name,
    cost_price = EXCLUDED.cost_price,
    product_status = EXCLUDED.product_status,
    launch_date = EXCLUDED.launch_date,
    dw_updated_at = CURRENT_TIMESTAMP;

-- C) Load dim_warehouse
INSERT INTO dwh.dim_warehouse (
    warehouse_id, warehouse_code, warehouse_name, city, state, country, capacity
)
SELECT 
    warehouse_id,
    warehouse_code,
    warehouse_name,
    city,
    state,
    country,
    capacity
FROM logistics.warehouses
ON CONFLICT (warehouse_id) DO NOTHING;

