-- ============================================================================
-- WEEK 3: TOPIC 3 — Conformed Dimensions with Surrogate Keys & -1 Fallbacks
-- Description:
-- Transforming your existing 3NF tables into Kimball Conformed Dimensions:
--   - customer.customers + customer.addresses ──► dwh.dim_customer
--   - catalog.products + catalog.categories   ──► dwh.dim_product
--   - logistics.warehouses                    ──► dwh.dim_warehouse
--
-- Key Dimensional Principles Illustrated:
-- 1. Denormalization: Flattening category into dim_product; flattening primary
--    address into dim_customer (eliminates costly multi-hop joins).
-- 2. Surrogate Primary Keys: Generated BIGINT identity keys decoupled from source UUIDs.
-- 3. Natural / Business Keys: UUIDs and operational codes retained for auditability.
-- 4. Mandatory -1 Record: Fallback row preventing pipeline failures on missing data.
-- 5. Address Window Function Deduplication: Selecting the single primary address.
-- ============================================================================

CREATE SCHEMA IF NOT EXISTS dwh;

-- ----------------------------------------------------------------------------
-- 1. DIM_CUSTOMER
-- ----------------------------------------------------------------------------
DROP TABLE IF EXISTS dwh.dim_customer CASCADE;

CREATE TABLE dwh.dim_customer (
    customer_sk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id UUID NOT NULL UNIQUE,          -- Operational UUID from customer.customers
    customer_code VARCHAR(50) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    first_name VARCHAR(60) NOT NULL,
    last_name VARCHAR(60) NOT NULL,
    email VARCHAR(150) NOT NULL,
    phone VARCHAR(50),
    customer_status VARCHAR(50) NOT NULL,
    signup_date DATE,
    address_line_1 VARCHAR(255),
    city VARCHAR(100) NOT NULL,
    state VARCHAR(100) NOT NULL,
    postal_code VARCHAR(30) NOT NULL,
    country VARCHAR(100) NOT NULL,
    dw_created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    dw_updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

